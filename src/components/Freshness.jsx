import React, { useEffect, useState } from 'react'
import { supabase } from '../lib/supabase.js'

// ============================================================================
// Когда данные обновлялись в последний раз.
//
// ЗАЧЕМ ЭТА СТРОКА СУЩЕСТВУЕТ. Импорты запускаются кнопками, вручную. Пока
// кнопку не нажали, кабинет показывает вчерашние цифры и выглядит ровно
// так же, как если бы они были сегодняшние. Ноль читается как «продаж не
// было», а не как «данные устарели», и отличить одно от другого человек
// не может — экран не говорит.
//
// Дважды за один день разбирали «пропавшие» сделки, и оба раза причина
// была одна: сделку оплатили после того, как отработал импорт. Эта строка
// отвечала бы на такой вопрос за секунду.
//
// ЦВЕТ МЕНЯЕТСЯ ПО ВОЗРАСТУ, а не по факту наличия данных: шесть часов —
// нормально, сутки — повод нажать кнопку, и об этом сказано словами.
// ============================================================================

function подпись(iso) {
  const d = new Date(iso)
  return d.toLocaleString('ru-RU', {
    day: '2-digit', month: 'long', hour: '2-digit', minute: '2-digit',
  })
}

export default function Freshness({ набор }) {
  const [обновлено, setОбновлено] = useState(undefined)

  useEffect(() => {
    let cancelled = false
    supabase.from('portal_freshness').select('набор, обновлено').eq('набор', набор)
      .then(({ data }) => {
        if (!cancelled) setОбновлено(data && data.length ? data[0].обновлено : null)
      })
    return () => { cancelled = true }
  }, [набор])

  // Пока не ответило — молчим. Мигать «данных нет» на полсекунды при каждом
  // открытии вкладки хуже, чем не показать ничего.
  if (обновлено === undefined) return null
  if (!обновлено) return <span className="freshness bad">данные ни разу не загружались</span>

  const часов = (Date.now() - new Date(обновлено).getTime()) / 3600000
  const tone = часов > 24 ? 'bad' : часов > 6 ? 'warn' : ''
  return (
    <span className={`freshness ${tone}`} title="Обновляется кнопкой в разделе «Импорт данных»">
      данные на {подпись(обновлено)}
      {часов > 24 && ' · пора обновить'}
    </span>
  )
}
