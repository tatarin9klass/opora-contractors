-- ============================================================================
-- Переводы из БФЛ зачисляются в одноимённые каналы Автоправа.
--
-- РЕШЕНИЕ РУКОВОДИТЕЛЯ НАПРАВЛЕНИЯ, принятое сознательно. В предыдущей
-- миграции эти сделки лежали отдельной группой «2.11 Перевод из БФЛ», потому
-- что расход на этих людей списан в направлении БФЛ, и зачисление договоров
-- в каналы Автоправа улучшает их CPO без соответствующего расхода. Возражение
-- было озвучено дважды и отклонено: с точки зрения направления важно, какой
-- рекламный канал привёл человека, а не в чьём бюджете лежат деньги.
--
-- Не возвращать обратно без разговора с ним.
--
--   Перевод из БФЛ: ofbfl-2ГИС ОПОРА (ЗВ)      → Avtpr. 2ГИС Опора (ЗВ)
--   Перевод из БФЛ: ofbfl-Сайт ОПОРА (заявка)  → Avtpr. Сайт Опора (заявка)
--   Перевод из БФЛ: ofbfl-Опора Я.Бизнес (ЗВ)  → Avtpr. Я.Биз Опора (ЗВ)
--
-- ПОБОЧНЫЙ ЭФФЕКТ, О КОТОРОМ НАДО ПОМНИТЬ ПРИ ЧТЕНИИ CPO: у каналов «2.2
-- Заявки 2гис», «2.1 Заявки сайт опора» и «2.7 Яндекс» прибавилось 11, 3 и 1
-- договор соответственно, а расход остался прежним. Их CPO стал лучше ровно
-- на эту величину, и часть этого улучшения оплачена бюджетом БФЛ.
-- ============================================================================

update ap_deal_source_overrides
set real_source = case real_source
  when 'Перевод из БФЛ: ofbfl-2ГИС ОПОРА (ЗВ)'     then 'Avtpr. 2ГИС Опора (ЗВ)'
  when 'Перевод из БФЛ: ofbfl-Сайт ОПОРА (заявка)' then 'Avtpr. Сайт Опора (заявка)'
  when 'Перевод из БФЛ: ofbfl-Опора Я.Бизнес (ЗВ)' then 'Avtpr. Я.Биз Опора (ЗВ)'
  else real_source
end
where real_source like 'Перевод из БФЛ:%';

-- Источники-посредники больше не нужны: ни одна сделка на них не ссылается.
delete from ap_sources where bitrix_name like 'Перевод из БФЛ:%';
delete from ap_channels where name = '2.11 Перевод из БФЛ';

-- Проверка: строк с переводами остаться не должно.
do $$
declare n integer;
begin
  select count(*) into n from ap_deal_source_overrides where real_source like 'Перевод из БФЛ:%';
  if n > 0 then
    raise exception 'Остались переводы из БФЛ: % строк', n;
  end if;
end $$;
