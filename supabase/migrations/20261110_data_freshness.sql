-- ============================================================================
-- Когда данные обновлялись в последний раз.
--
-- ЗАЧЕМ. Импорты запускаются кнопками, вручную. Пока кнопку не нажали,
-- кабинет показывает честные цифры вчерашнего дня — и ничем не отличается
-- от кабинета, где цифры сегодняшние. Дважды за один день разбирались с
-- «пропавшими» сделками, и оба раза причина была одна: сделку оплатили
-- после того, как отработал импорт.
--
-- Ноль на экране читается как «продаж не было». Отличить его от «данные
-- устарели» человек не может, и это не его вина — экран не сказал.
--
-- Свежесть берётся из самих данных (synced_at на строках), а не из
-- журнала запусков: журнал скажет, что импорт стартовал, а строки
-- скажут, что он действительно что-то записал.
-- ============================================================================
drop view if exists data_freshness cascade;
create view data_freshness as
select 'Сделки отдела продаж'::text as набор, max(synced_at) as обновлено from rop_deals
union all
select 'Агентская сеть'::text, max(synced_at) from agent_cards;

revoke all on data_freshness from anon, authenticated;

drop view if exists portal_freshness;
create view portal_freshness as
select f.* from data_freshness f
where rop_can_read() or agents_can_read();

revoke all on portal_freshness from anon;
grant select on portal_freshness to authenticated;

