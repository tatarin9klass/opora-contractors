-- ============================================================================
-- Через сколько возвращаются к человеку, который взял трубку.
--
-- ЗАЧЕМ ПЕРЕДЕЛКА. Предыдущая витрина bfl_dozvon_callback_discipline мерила
-- не то, что задумывалось, и это видно по её же результату: группа
-- «зафиксирована и выполнена» дала конверсию 7,0% — хуже всех.
--
-- Причина в семантике Битрикса: выполненный запланированный звонок перестаёт
-- быть запланированным, у него COMPLETED меняется на 'Y'. Значит
-- незавершённые активности — это не «записанные договорённости», а только
-- ТЕ, ЧТО ДО СИХ ПОР ВИСЯТ НЕВЫПОЛНЕННЫМИ. Выполненные перезвоны попали в
-- группу «договорённость не зафиксирована» и смешались с теми, где плана не
-- было вовсе. Трёхчастное деление оказалось бессмысленным.
--
-- Из той витрины остаётся ровно один достоверный факт, не зависящий от
-- классификации: открытая следующая задача есть лишь у 13,2% достигнутых
-- лидов (352 из 2673). У 87% людей, которые взяли трубку, в системе не
-- записано ни одного следующего шага.
--
-- ЧТО МЕРЯЕМ ВМЕСТО ЭТОГО. Время от момента, когда человек взял трубку
-- (вход в стадию «Дозвонились» — метка, которую ставит сам менеджер), до
-- следующего касания. Здесь никакой двусмысленности нет: либо вернулись
-- быстро, либо нет, и это видно по датам звонков.
--
-- Смысл стадии: трубку взяли, но момент неподходящий — «занят,
-- перезвоните», «я на даче». Такой человек ждёт обратного звонка, и вся
-- ставка в том, насколько быстро его сделали.
--
-- ВАЖНО ПРО ПРИЧИННОСТЬ. Быстрый возврат может не улучшать конверсию, а
-- доставаться тем, кто и так перспективен: менеджер слышит интерес и
-- перезванивает скорее. Поэтому ниже есть разрез по источникам — если
-- преимущество быстрого возврата держится внутри каждого источника, версия
-- «просто лиды получше» слабеет. Доказательством это не станет, доказать
-- можно только экспериментом, но отличить сильный эффект от артефакта
-- позволяет.
-- ============================================================================

-- ============================================================================
-- Базовая таблица: когда взяли трубку, когда вернулись, чем кончилось
-- ============================================================================
drop view if exists bfl_dozvon_next_touch cascade;
create view bfl_dozvon_next_touch with (security_invoker = true) as
with entry as (
  select b.lead_id, b.moment, l.source_marker
  from bfl_dozvon_labels b
  join bfl_lead_timings l on l.lead_id = b.lead_id
  where b.класс = 'дозвонились'
),
-- кто разговаривал перед тем, как поставить метку: спрос за возврат с него
owner as (
  select lead_id, responsible_name
  from (
    select
      e.lead_id,
      c.responsible_name,
      row_number() over (partition by e.lead_id order by c.started_at desc, c.id desc) as rn
    from entry e
    join bfl_lead_calls c on c.lead_id = e.lead_id
    where bfl_call_is_attempt(c.direction, c.completed)
      and c.started_at is not null
      and c.started_at <= e.moment
  ) t
  where rn = 1
),
touch as (
  select
    e.lead_id,
    e.moment,
    e.source_marker,
    min(c.started_at) filter (
      where c.started_at > e.moment
    ) as следующая_попытка,
    min(c.started_at) filter (
      where c.started_at > e.moment
        and bfl_call_dialogue(c.has_recording, c.duration_sec)
    ) as следующий_разговор,
    count(c.id) filter (where c.started_at > e.moment)::integer as попыток_после
  from entry e
  left join bfl_lead_calls c
    on c.lead_id = e.lead_id
   and bfl_call_is_attempt(c.direction, c.completed)
   and c.started_at is not null
  group by 1, 2, 3
)
select
  t.lead_id,
  t.source_marker,
  o.responsible_name as кто_дозвонился,
  t.moment as взяли_трубку,
  t.следующая_попытка,
  t.попыток_после,
  round(extract(epoch from (t.следующая_попытка - t.moment)) / 86400.0, 2) as дней_до_возврата,
  (q.qual_at is not null and q.qual_at > t.moment) as стал_квалом
from touch t
left join owner o on o.lead_id = t.lead_id
left join bfl_lead_qual_moment q on q.lead_id = t.lead_id;

-- ============================================================================
-- Главное: насколько скорость возврата связана с квалом
-- ============================================================================
drop view if exists bfl_callback_latency;
create view bfl_callback_latency with (security_invoker = true) as
select
  case
    when следующая_попытка is null then '9. не вернулись никогда'
    when дней_до_возврата < 0.25 then '1. в течение 6 часов'
    when дней_до_возврата < 1 then '2. в тот же день'
    when дней_до_возврата < 2 then '3. на следующий день'
    when дней_до_возврата < 4 then '4. через 2-3 дня'
    when дней_до_возврата < 8 then '5. через 4-7 дней'
    when дней_до_возврата < 31 then '6. через 8-30 дней'
    else '7. позже месяца'
  end as когда_вернулись,
  count(*)::integer as лидов,
  count(*) filter (where стал_квалом)::integer as квалов,
  round(100.0 * count(*) filter (where стал_квалом) / nullif(count(*), 0), 1)
    as конверсия_в_квал,
  round(avg(попыток_после)::numeric, 1) as среднее_попыток_после
from bfl_dozvon_next_touch
group by 1;

-- ============================================================================
-- Та же связь внутри источников
--
-- Контроль против версии «быстро перезванивают тем, кто и так хорош».
-- Если преимущество быстрого возврата держится внутри каждого источника,
-- версия слабеет.
-- ============================================================================
drop view if exists bfl_callback_latency_by_source;
create view bfl_callback_latency_by_source with (security_invoker = true) as
select
  source_marker as источник,
  count(*)::integer as достигнуто_лидов,
  count(*) filter (where дней_до_возврата < 1)::integer as вернулись_в_тот_же_день,
  round(100.0 * count(*) filter (where стал_квалом and дней_до_возврата < 1)
        / nullif(count(*) filter (where дней_до_возврата < 1), 0), 1) as конверсия_быстрых,
  count(*) filter (where дней_до_возврата >= 1 or следующая_попытка is null)::integer as вернулись_позже_или_никогда,
  round(100.0 * count(*) filter (where стал_квалом and (дней_до_возврата >= 1 or следующая_попытка is null))
        / nullif(count(*) filter (where дней_до_возврата >= 1 or следующая_попытка is null), 0), 1)
    as конверсия_медленных
from bfl_dozvon_next_touch
where source_marker is not null
group by 1;

-- ============================================================================
-- Кто быстро возвращается к людям, которых сам же и достал
--
-- Спрос именно с того, кто разговаривал перед постановкой метки: он слышал
-- «перезвоните вечером» и он же отвечает за то, чтобы вечером позвонить.
-- ============================================================================
drop view if exists bfl_callback_latency_by_manager;
create view bfl_callback_latency_by_manager with (security_invoker = true) as
select
  coalesce(кто_дозвонился, '— не загружен —') as менеджер,
  count(*)::integer as достал_людей,
  round((percentile_cont(0.5) within group (order by дней_до_возврата))::numeric, 2)
    as медиана_дней_до_возврата,
  count(*) filter (where дней_до_возврата < 1)::integer as вернулся_в_тот_же_день,
  round(100.0 * count(*) filter (where дней_до_возврата < 1) / nullif(count(*), 0), 1)
    as доля_быстрых_возвратов,
  count(*) filter (where следующая_попытка is null)::integer as не_вернулся_совсем,
  round(100.0 * count(*) filter (where стал_квалом) / nullif(count(*), 0), 1)
    as конверсия_в_квал
from bfl_dozvon_next_touch
group by 1;

