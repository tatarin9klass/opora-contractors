-- ============================================================================
-- Окончательный порог дозвона: 15 секунд.
--
-- ОТКУДА ЦИФРА. Калибровка по разметке менеджеров на уровне отдельных
-- звонков: положительный класс — тот звонок, после которого поставлена метка
-- «Дозвонились» (2616 штук), отрицательный — все звонки лидов, помеченных
-- «не отвечает более месяца» (73 970 штук).
--
--   порог    поймали дозвон   ложных   разделение
--     5 с        91,4%         40,9%      50,5
--    10 с        83,5%         20,0%      63,5
--    15 с        72,1%         11,0%      61,1   ← берём
--    20 с        61,8%          7,1%      54,7
--    35 с        38,6%          2,1%      36,5   ← было
--
-- Максимум разделения на 10 секундах, но берём 15: отношение верных к ложным
-- там 6,6 против 4,2, то есть цифры заметно чище, а разделения теряем 2,4
-- пункта. Для сравнений между менеджерами и источниками чистота важнее.
--
-- ЧЕМ ОКАЗАЛСЯ ОТРИЦАТЕЛЬНЫЙ КЛАСС. Две трети его — вообще не разговоры:
--   35,1%  ровно 0 секунд, записей 1 на 25 930 звонков — чистые гудки;
--   37,7%  1-9 секунд, и запись есть почти у каждого — автоответ оператора
--          связи, «аппарат абонента выключен», записанный как разговор.
-- Именно эти сто тысяч звонков и давали когда-то неправдоподобные 74% связи
-- при правиле «есть запись — значит дозвон».
--
-- ПОЧЕМУ 35 СЕКУНД БЫЛО СЛИШКОМ МНОГО. Типичный дозвон здесь — «занят,
-- перезвоните», «я на даче», и это 10-35 секунд. Порог в 35 секунд ловил
-- 38,6% настоящих дозвонов, порог в 60 — 22,3%.
--
-- РАЗДЕЛЕНИЕ ПОНЯТИЙ, которое теперь надо держать твёрдо:
--   bfl_call_answered  (от 15 с) — ДОЗВОН: человек взял трубку;
--   bfl_call_dialogue  (от 60 с) — КВАЛИФИКАЦИОННЫЙ РАЗГОВОР: говорили по
--                                  делу. Такие разговоры дают квал в 50-55%
--                                  случаев одинаково на всех стадиях, так
--                                  что это осмысленная величина, а не
--                                  «недоделанный дозвон».
--
-- ВАЖНО ПРО СМЕЩЕНИЕ. На пороге 15 секунд доля ложных 11,0%, и измеренная
-- доля дозвона всегда будет завышена примерно на 11% от числа недозвонов.
-- Для сравнений это неважно — смещение одинаково для всех. Для абсолютной
-- величины поправка такая: истинная доля = (измеренная − 0,110) / (0,721 −
-- 0,110). Пользоваться ею стоит только если понадобится назвать абсолютное
-- число снаружи.
--
-- Порог останется приближением, пока вебхуку не выдадут право «Телефония»:
-- тогда вместо длительности придёт код завершения вызова, и обе функции
-- перепишутся на него.
-- ============================================================================

-- Правка только функции: все витрины — по менеджерам, источникам, часам,
-- стадиям и профилю попыток — зовут её и пересчитаются сами. Ради этого она
-- с самого начала и была функцией, а не константой в шести местах.
create or replace function bfl_call_answered(has_rec boolean, dur integer)
returns boolean language sql immutable as $$
  select coalesce(has_rec, false) and dur is not null and dur >= 15 and dur <= 3600;
$$;

comment on function bfl_call_answered(boolean, integer) is
  'Дозвон: человек взял трубку. Порог 15 секунд откалиброван по разметке '
  'менеджеров на уровне звонков: ловит 72,1% дозвонов при 11,0% ложных. '
  'Ниже 10 секунд лежит автоответ оператора связи, который пишется как '
  'разговор. Не путать с bfl_call_dialogue — там квалификационный разговор.';

comment on function bfl_call_dialogue(boolean, integer) is
  'Квалификационный разговор: говорили по делу, от 60 секунд. Это 19,8% '
  'дозвонов. Такие разговоры дают квал в 50-55% случаев одинаково на всех '
  'стадиях воронки.';
