-- ============================================================================
-- Скорость возврата: причина или отбор?
--
-- ПРОТИВОРЕЧИЕ, РАДИ КОТОРОГО ВСЁ ЭТО. Два замера разошлись.
--
-- На уровне лида связь сильная: вернулись в тот же день — 19,7% квала,
-- позже — 9,4%, не вернулись — 2,2%. И она держится ВНУТРИ КАЖДОГО из 17
-- источников, разрыв от +5,7 до +21,4 пункта, семнадцать из семнадцати в
-- одну сторону. Состав лидов её не объясняет.
--
-- На уровне менеджера связи нет вовсе: корреляция доли быстрых возвратов с
-- конверсией в квал равна +0,006. Островская, лучшая по сквозной
-- эффективности, по скорости возврата ПОСЛЕДНЯЯ.
--
-- Простейшее объяснение расхождения — отбор: менеджер перезванивает быстро
-- тем, кто в разговоре показался перспективным. Тогда внутри работы каждого
-- человека быстрые конвертируются лучше не из-за скорости, а из-за отбора, и
-- норматив «перезванивать всем в тот же день» не даст ничего. Отбор работает
-- внутри источника так же, как внутри менеджера, поэтому контроль по
-- источникам его и не поймал.
--
-- КАК РАЗВЕСТИ. Нужен фактор, который меняет скорость возврата и при этом не
-- зависит от перспективности лида. Такой есть — ЧАС, В КОТОРЫЙ ЧЕЛОВЕК ВЗЯЛ
-- ТРУБКУ. Ответил в десять утра — перезвонить в тот же день легко; ответил в
-- семь вечера — почти невозможно, независимо от того, насколько он интересен.
--
-- Читается однозначно:
--   доля возвратов ниже И конверсия ниже  → скорость действительно причина;
--   доля возвратов ниже, конверсия та же  → эффект был отбором.
--
-- Это не эксперимент и строгим доказательством не станет: вечерние звонящие
-- могут отличаться от утренних и сами по себе. Но предположение здесь куда
-- слабее, чем «быстрый возврат случаен», и для решения о пилоте этого
-- хватает.
--
-- ПОПРАВКА К ПРЕДЫДУЩЕЙ ВИТРИНЕ. В bfl_callback_latency «в тот же день»
-- означало «в пределах 24 часов», а не календарный день. Для часового
-- разреза это принципиально: возврат через 20 часов после вечернего звонка —
-- это следующее утро, а не тот же вечер. Поэтому здесь считается именно
-- календарный день по новосибирскому времени.
-- ============================================================================

drop view if exists bfl_callback_by_pickup_hour;
create view bfl_callback_by_pickup_hour with (security_invoker = true) as
select
  extract(hour from (взяли_трубку at time zone 'Asia/Novosibirsk'))::integer as час_когда_взяли_трубку,
  count(*)::integer as лидов,
  count(*) filter (
    where (следующая_попытка at time zone 'Asia/Novosibirsk')::date
        = (взяли_трубку at time zone 'Asia/Novosibirsk')::date
  )::integer as вернулись_в_тот_же_день,
  round(100.0 * count(*) filter (
    where (следующая_попытка at time zone 'Asia/Novosibirsk')::date
        = (взяли_трубку at time zone 'Asia/Novosibirsk')::date
  ) / nullif(count(*), 0), 1) as доля_возвратов_в_день,
  count(*) filter (where стал_квалом)::integer as квалов,
  round(100.0 * count(*) filter (where стал_квалом) / nullif(count(*), 0), 1)
    as конверсия_в_квал
from bfl_dozvon_next_touch
where взяли_трубку is not null
group by 1;

-- ============================================================================
-- Та же связь, но в календарных днях — чтобы сравнивать с часовым разрезом
-- на одном определении
-- ============================================================================
drop view if exists bfl_callback_latency_calendar;
create view bfl_callback_latency_calendar with (security_invoker = true) as
with d as (
  select
    стал_квалом,
    попыток_после,
    case
      when следующая_попытка is null then null
      else (следующая_попытка at time zone 'Asia/Novosibirsk')::date
         - (взяли_трубку at time zone 'Asia/Novosibirsk')::date
    end as дней
  from bfl_dozvon_next_touch
  where взяли_трубку is not null
)
select
  case
    when дней is null then '9. не вернулись никогда'
    when дней = 0 then '1. в тот же календарный день'
    when дней = 1 then '2. на следующий день'
    when дней <= 3 then '3. через 2-3 дня'
    when дней <= 7 then '4. через 4-7 дней'
    when дней <= 30 then '5. через 8-30 дней'
    else '6. позже месяца'
  end as когда_вернулись,
  count(*)::integer as лидов,
  count(*) filter (where стал_квалом)::integer as квалов,
  round(100.0 * count(*) filter (where стал_квалом) / nullif(count(*), 0), 1)
    as конверсия_в_квал,
  round(avg(попыток_после)::numeric, 1) as среднее_попыток_после
from d
group by 1;
