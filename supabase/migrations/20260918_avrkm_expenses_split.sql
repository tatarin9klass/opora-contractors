-- ============================================================================
-- Аварком: расход за январь–май разложен по каналам.
--
-- Выполнять ПОСЛЕ 20260918_avrkm_channels.sql — там создаются сами каналы
-- 3.1/3.2/3.3, без них этому скрипту не к чему присоединяться.
--
-- Разбивка взята из Roistat, по источникам. Каждый месяц сходится с итогом,
-- который до этого висел на аваркоме целиком:
--   январь  405 427 + 152 300           = 557 727
--   февраль 405 427 + 192 833 +  74 000 = 672 260
--   март    405 427 + 200 333 +  80 000 = 685 760
--   апрель  405 427 + 153 333 + 177 200 = 735 960
--   май     415 225 +  15 333 + 240 050 = 670 608
-- Июнь и июль разложены раньше, в миграции с каналами.
-- ============================================================================

insert into ap_monthly_expenses (channel_id, month, spend)
select c.id, v.month::date, v.spend
from (values
  ('3.1 2ГИС',          '2026-01-01', 405427),
  ('3.2 Яндекс директ', '2026-01-01', 152300),
  ('3.3 От Комиссара',  '2026-01-01',      0),

  ('3.1 2ГИС',          '2026-02-01', 405427),
  ('3.2 Яндекс директ', '2026-02-01', 192833),
  ('3.3 От Комиссара',  '2026-02-01',  74000),

  ('3.1 2ГИС',          '2026-03-01', 405427),
  ('3.2 Яндекс директ', '2026-03-01', 200333),
  ('3.3 От Комиссара',  '2026-03-01',  80000),

  ('3.1 2ГИС',          '2026-04-01', 405427),
  ('3.2 Яндекс директ', '2026-04-01', 153333),
  ('3.3 От Комиссара',  '2026-04-01', 177200),

  ('3.1 2ГИС',          '2026-05-01', 415225),
  ('3.2 Яндекс директ', '2026-05-01',  15333),
  ('3.3 От Комиссара',  '2026-05-01', 240050)
) as v(channel_name, month, spend)
join ap_channels c on c.name = v.channel_name
on conflict (channel_id, month) do update set spend = excluded.spend, updated_at = now();

-- Корзина нераспределённого расхода больше не нужна: источников на ней нет,
-- весь расход разнесён по каналам. Удаление каскадом снимает и её строки в
-- ap_monthly_expenses — в них теперь ровно те же деньги, что уже лежат на
-- каналах, и если их оставить, итог по группе АВАРКОМ удвоится.
delete from ap_channels where name = '3.9 Аварком — нераспределённый расход';
