-- Стадии, которые встречаются в данных, но в памятке не описаны. Пустой
-- результат — памятка полная. Непустой — в Битриксе появилась или
-- переименовалась стадия, и подрядчик увидит её без объяснения.
drop view if exists portal_stage_guide_gaps;
create view portal_stage_guide_gaps with (security_invoker = true) as
select
  l.status_name as стадия_без_описания,
  count(*)::integer as лидов,
  max(l.created_at)::date as последний_лид
from bfl_lead_timings l
where l.status_name is not null
  and not exists (
    select 1 from bfl_lead_stage_guide g where g.status_name = l.status_name
  )
group by l.status_name;

-- ============================================================================
-- Кому принадлежит источник
--
-- Внутренняя вьюха: нужна и дашборду, и выгрузке, а дублировать сопоставление
-- в двух местах — значит однажды поправить одно и забыть второе.
--
-- ОДИН МАРКЕР — ОДИН ПОДРЯДЧИК, ИНАЧЕ НИ ОДНОМУ. В таблице sources есть
-- маркеры, записанные дважды на разных подрядчиков (проверено: как минимум
-- «ofbfl-перевод из автоправа», «ofbfl-электронная почта», «ofbfl-другое
-- (см.комментарий)»). Для аналитики это неточность, а для кабинета — утечка:
-- лид показался бы чужому подрядчику. Поэтому неоднозначный маркер НЕ
-- отдаётся никому, а попадает в portal_source_conflicts. Такой маркер надо
-- расчистить в справочнике ДО выдачи доступа.
--
-- Прав ни anon, ни authenticated на эту вьюху нет: читают её только вьюхи
-- portal_*, работающие с правами владельца.
-- ============================================================================
drop view if exists portal_source_owner cascade;
create view portal_source_owner as
select
  lower(s.roistat_marker) as marker_lower,
  min(s.contractor_id::text)::uuid as contractor_id,
  count(distinct s.contractor_id)::integer as contractors_count
from sources s
where s.roistat_marker is not null
  and s.contractor_id is not null
group by lower(s.roistat_marker);

revoke all on portal_source_owner from anon, authenticated;

drop view if exists portal_source_conflicts;
create view portal_source_conflicts with (security_invoker = true) as
select
  s.roistat_marker as маркер,
  count(distinct s.contractor_id)::integer as подрядчиков,
  string_agg(distinct c.name, ', ') as кто_претендует
from sources s
join contractors c on c.id = s.contractor_id
where s.roistat_marker is not null and s.contractor_id is not null
group by s.roistat_marker
having count(distinct s.contractor_id) > 1;

comment on view portal_source_conflicts is
  'Маркеры, записанные на нескольких подрядчиков. Пока маркер здесь, его '
  'лиды не видны в кабинете НИКОМУ — показать их значило бы отдать чужие.';

-- ============================================================================
-- Кабинет: кто я
-- ============================================================================
-- Колонки вьюх кабинета названы латиницей, в отличие от аналитических вьюх
-- направления. Причина не в стиле: по этим колонкам идут фильтр по периоду и
-- сортировка через PostgREST, то есть имена уезжают в URL запроса. Русские
-- заголовки живут в интерфейсе и в заголовках выгрузки.
drop view if exists portal_my_profile;
create view portal_my_profile as
select
  c.id as contractor_id,
  c.name as contractor_name,
  p.email,
  p.password_expires_at,
  (select count(*)::integer from sources s
    where s.contractor_id = c.id and s.status = 'активен') as active_sources
from profiles p
join contractors c on c.id = p.contractor_id
where p.id = auth.uid()
  and c.id = current_contractor_id();

revoke all on portal_my_profile from anon;
grant select on portal_my_profile to authenticated;

-- ============================================================================
-- Кабинет: дашборд по НАШЕЙ отчётной логике
--
-- Квал — по дате квалификации, встреча — по дате встречи, договор — по дате
-- оплаты, лид — по дате создания. Источник — та же daily_facts, по которой
-- считает дашборд направления, поэтому цифры подрядчика и наши совпадают
-- строка в строку. Это важнее удобства: расхождение «у вас так, у нас иначе»
-- стоит дороже любой красивой витрины.
--
-- Выручки и расхода здесь нет и не будет. Дубли есть намеренно: подрядчик
-- должен видеть, сколько его заявок мы признали повторными, иначе спорить ему
-- не с чем.
-- ============================================================================
drop view if exists portal_my_daily;
create view portal_my_daily as
select
  f.fact_date,
  f.source_marker,
  sum(f.leads)::integer as leads,
  sum(f.quals)::integer as quals,
  sum(f.meetings)::integer as meetings,
  sum(f.deals)::integer as deals,
  sum(coalesce(f.duplicates, 0))::integer as duplicates
from daily_facts f
where f.contractor_id = current_contractor_id()
group by f.fact_date, f.source_marker;

revoke all on portal_my_daily from anon;
grant select on portal_my_daily to authenticated;

comment on view portal_my_daily is
  'Дашборд кабинета: наша отчётная логика (квал по дате квала, встреча по '
  'дате встречи). С выгрузкой по датам НЕ сходится — см. portal_my_leads.';

-- ============================================================================
-- Кабинет: выгрузка построчно
--
-- По дате СОЗДАНИЯ лида, со стадией на СЕЙЧАС. Ровно пять полей, как
-- заказано: телефон, дата и время создания, стадия, UTM, и памятка по
-- стадиям идёт отдельным листом.
--
-- UTM собирается в одну метку для чтения человеком и тут же лежит по полям —
-- одна и та же заявка в разных системах разбирается по-разному, и спорить
-- удобнее по полям, а читать — по строке.
--
-- ЧЕГО В ВЫГРУЗКЕ НЕТ: ни имени клиента, ни ответственного менеджера, ни
-- комментариев, ни суммы договора. Телефон — единственная персональная
-- колонка, и она здесь по прямому решению.
-- ============================================================================
drop view if exists portal_my_leads;
create view portal_my_leads as
select
  l.lead_id,
  l.created_at,
  l.phone,
  l.source_marker,
  coalesce(l.status_name, '— не определена —') as stage,
  coalesce(g.is_qual, false) as is_qual,
  l.utm_source,
  l.utm_medium,
  l.utm_campaign,
  l.utm_content,
  l.utm_term,
  nullif(concat_ws(' / ',
    nullif(l.utm_source, ''), nullif(l.utm_medium, ''),
    nullif(l.utm_campaign, ''), nullif(l.utm_content, ''),
    nullif(l.utm_term, '')
  ), '') as utm
from bfl_lead_timings l
join portal_source_owner o
  on o.marker_lower = lower(l.source_marker)
 and o.contractors_count = 1
left join bfl_lead_stage_guide g on g.status_name = l.status_name
where o.contractor_id = current_contractor_id();

revoke all on portal_my_leads from anon;
grant select on portal_my_leads to authenticated;

comment on view portal_my_leads is
  'Выгрузка кабинета: лиды по дате СОЗДАНИЯ, стадия — фактическая на сейчас. '
  'С дашбордом по датам НЕ сходится, это разные вопросы. Данные есть с '
  '2026-04-01 — раньше построчная история не импортировалась.';

-- ============================================================================
-- Кабинет: памятка по стадиям
-- ============================================================================
drop view if exists portal_stage_guide;
create view portal_stage_guide as
select g.status_name, g.is_qual, g.description, g.sort_order
from bfl_lead_stage_guide g
where current_contractor_id() is not null;

revoke all on portal_stage_guide from anon;
grant select on portal_stage_guide to authenticated;

-- --- Индексы под запросы кабинета -------------------------------------------
-- Кабинет всегда спрашивает период по дате создания и всегда по своему
-- источнику. Индекс по created_at уже есть, добавляем источник.
create index if not exists bfl_lead_timings_source_created_idx
  on bfl_lead_timings(source_marker, created_at);

-- ============================================================================
-- Проверка перед выдачей доступа
--
--   select * from portal_source_conflicts;   -- должно быть пусто
--   select * from portal_stage_guide_gaps;   -- должно быть пусто
--   select * from portal_security_audit;     -- должно быть пусто
--
-- Если в первой есть строки — у подрядчика пропадут лиды по этим маркерам.
-- Это сделано сознательно: пропавший лид — спор, показанный чужой — утечка.
-- ============================================================================
