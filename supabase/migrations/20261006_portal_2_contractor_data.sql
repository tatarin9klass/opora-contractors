-- ============================================================================
-- Кабинет подрядчика: данные, которые он видит. Направление БФЛ.
--
-- УСТРОЙСТВО. Подрядчик не имеет ни одной политики ни на одной базовой
-- таблице (см. предыдущую миграцию). Он видит ровно пять вьюх portal_*, и
-- каждая из них сама фильтрует по current_contractor_id(). Это сделано не из
-- вкуса, а потому что в RLS нельзя закрыть отдельную КОЛОНКУ: дав подрядчику
-- доступ к daily_facts «только по своим строкам», мы отдали бы вместе со
-- строками и выручку, а дав доступ к sources — ставку за лид и абонентку.
-- Вьюха же отдаёт ровно перечисленные колонки, и проверка безопасности
-- сводится к чтению пяти списков select.
--
-- ПОЧЕМУ ВЬЮХИ БЕЗ security_invoker. Здесь это единственный случай, когда так
-- правильно, и причина именно в этом: вьюха должна читать таблицы, к которым
-- у подрядчика доступа нет совсем. Защита перенесена внутрь — у каждой вьюхи
-- в where стоит сравнение с current_contractor_id(), которая возвращает NULL
-- для всех, кроме подрядчика с действующим паролем. Сравнение с NULL никогда
-- не истинно, поэтому ни аноним, ни сотрудник, ни подрядчик с просроченным
-- паролем не получат ни строки. Права anon на эти вьюхи всё равно отзываются
-- отдельно — в два слоя.
--
-- ДВЕ РАЗНЫЕ ЛОГИКИ ДАТ, И ЭТО НАМЕРЕННО:
--
--   ДАШБОРД (portal_my_daily) — наша отчётная логика. Лид считается в день
--   создания, квал — в день КВАЛИФИКАЦИИ, встреча — в день ВСТРЕЧИ, договор —
--   в день оплаты. Так считает всё приложение и так принимаются решения по
--   бюджету. Лид, пришедший 1 сентября и отквалившийся 20-го, даёт лида в
--   первое число и квала в двадцатое.
--
--   ВЫГРУЗКА (portal_my_leads) — построчно по ДАТЕ СОЗДАНИЯ лида, со его
--   ФАКТИЧЕСКОЙ стадией на сейчас. Это нужно подрядчику для другого: сверить
--   свою отправку с нашим приёмом и посмотреть, чем кончились именно те
--   заявки, которые он сдал в эти дни.
--
--   ПОЭТОМУ ДВА ЧИСЛА НЕ СОЙДУТСЯ, И ЭТО НЕ ОШИБКА. За сентябрь в выгрузке
--   будет столько квалов, сколько сентябрьских лидов отквалилось КОГДА
--   УГОДНО, а на дашборде — сколько квалов случилось В СЕНТЯБРЕ, включая
--   августовские лиды. Расхождение надо подписать на самом экране, иначе
--   первый же подрядчик позвонит с вопросом, какая цифра настоящая. Обе.
--
-- ЧТО ПОДРЯДЧИК НЕ ВИДИТ НИ ПРИ КАКИХ УСЛОВИЯХ: расход, выручку, стоимость
-- лида и квала, свою ставку, других подрядчиков, менеджеров, Автоправо,
-- Аварком. Этих колонок нет в select — не скрыты на экране, а отсутствуют в
-- ответе базы.
--
-- ТЕЛЕФОН ЦЕЛИКОМ — по прямому решению: эти номера подрядчик нам и передаёт,
-- он их первично обрабатывает, и персональные данные у него уже есть.
-- Маскировать то, что человек отдал сам, смысла нет.
-- ============================================================================

-- --- Телефон и UTM в построчных данных по лидам ------------------------------
-- Колонки заводятся здесь, заполняет их Edge Function bfl-timings (там же
-- правка выборки полей Битрикса). До первого прогона функции выгрузка будет с
-- пустыми UTM — это ожидаемо, а не поломка.
alter table bfl_lead_timings
  add column if not exists phone text,
  add column if not exists utm_source text,
  add column if not exists utm_medium text,
  add column if not exists utm_campaign text,
  add column if not exists utm_content text,
  add column if not exists utm_term text;

comment on column bfl_lead_timings.phone is
  'Первый номер из многозначного поля PHONE лида. Отдаётся подрядчику в '
  'выгрузке целиком — по решению руководителя: номера он нам и передаёт.';

-- ============================================================================
-- Памятка по стадиям
--
-- КЛЮЧ — НАЗВАНИЕ, А НЕ КОД. Код стадии в Битриксе выглядит как UC_GKWGR0, и
-- сопоставлять его с названиями вручную — верный способ однажды подписать
-- стадию неправильно. Названия импорт берёт прямо из crm.status.list, то есть
-- они по определению совпадают с Битриксом. Если в Битриксе стадию
-- переименуют, строка перестанет находиться — и это будет видно в
-- portal_stage_guide_gaps ниже, а не молча испортит памятку.
--
-- ПРО ОТМЕТКУ «КВАЛ». Она проставлена по тому, как считает направление: четыре
-- стадии означают, что заявка признана квалифицированной. ВНИМАНИЕ: это не
-- то же самое, что дата квала в дашборде — она берётся из отдельного поля
-- Битрикса, которое ставит менеджер. Поэтому лид может стоять на стадии с
-- отметкой КВАЛ, но не иметь даты квалификации, и наоборот. В выгрузке
-- показывается стадия, в дашборде — дата; расхождение возможно и объяснимо.
-- ============================================================================
create table if not exists bfl_lead_stage_guide (
  status_name text primary key,
  sort_order integer not null,
  is_qual boolean not null default false,
  description text not null
);

alter table bfl_lead_stage_guide enable row level security;
drop policy if exists "staff_select" on bfl_lead_stage_guide;
create policy "staff_select" on bfl_lead_stage_guide for select using (is_staff());
drop policy if exists "admin_write" on bfl_lead_stage_guide;
create policy "admin_write" on bfl_lead_stage_guide for all
  using (is_admin()) with check (is_admin());

