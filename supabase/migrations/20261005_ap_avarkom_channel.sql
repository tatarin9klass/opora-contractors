-- ============================================================================
-- Поток из Аваркома выносится из «Прочего» в собственную группу.
--
-- ЧТО ВСКРЫЛ РАЗБОР. В канале «2.8 Прочее» оказались два источника с
-- заметным объёмом, растворённые среди мусора и неопознанных заявок:
--
--     Avtpr. Перевод из Аварком   19 договоров за 2026
--     Avtpr. Яма от комиссара      6 договоров за 2026
--
-- Девятнадцать договоров — больше, чем у некоторых отдельных каналов
-- Автоправа. Пока они лежат в «Прочем», по ним не видно ни динамики, ни
-- эффективности, а само «Прочее» выглядит крупнее, чем заслуживает.
--
-- ОДНА ГРУППА, ДВА ИСТОЧНИКА. Сценарии разные: «Перевод из Аварком» — это
-- переданный клиент, которого уже вели коллеги, а «Яма от комиссара» — заявка,
-- которую комиссар нашёл на выезде. Но источник потока один, и управленческий
-- вопрос к нему тоже один: сколько даёт смежное направление. Поэтому группа
-- общая, а разбивка видна при раскрытии строки.
--
-- Это правка справочника каналов, а не данных: она меняет только то, в какой
-- группе показываются договоры, и действует одинаково с включённой сверкой и
-- без неё. Исторические цифры «Прочего» уменьшатся на ту же величину, на
-- которую вырастет новая группа — за всю историю это 18 и 14 договоров.
-- ============================================================================

insert into ap_channels (name, direction, sort_order, from_correction) values
  ('2.13 Из Аваркома', 'avtpr', 213, false)
on conflict (name) do update set sort_order = excluded.sort_order;

update ap_sources
set channel_id = (select id from ap_channels where name = '2.13 Из Аваркома')
where bitrix_name in ('Avtpr. Перевод из Аварком', 'Avtpr. Яма от комиссара');

-- Проверка: оба источника должны уехать, иначе миграция отработала впустую.
do $$
declare n integer;
begin
  select count(*) into n
  from ap_sources s
  join ap_channels c on c.id = s.channel_id
  where s.bitrix_name in ('Avtpr. Перевод из Аварком', 'Avtpr. Яма от комиссара')
    and c.name = '2.13 Из Аваркома';
  if n <> 2 then
    raise exception 'Ожидалось 2 источника в «2.13 Из Аваркома», оказалось %', n;
  end if;
end $$;
