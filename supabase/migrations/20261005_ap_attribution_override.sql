-- ============================================================================
-- Разовая сверка источников по выигранным сделкам Автоправо.
--
-- ЗАЧЕМ. В выгрузке 120 выигранных сделок за январь-сентябрь 2026 обнаружился
-- не разрозненный брак, а системная подмена: при переводе лида из БФЛ в
-- Автоправо источник перезаписывается на «Avtpr. Рекомендация», а настоящий
-- остаётся только в свободном тексте поля «Дополнительно об источнике» —
-- робот сам пишет «Смена с источника ofbfl-2ГИС ОПОРА (ЗВ) при переводе в
-- Автоправо». То есть восстановить можно всё, но лечить надо правилом, а не
-- задним числом.
--
-- Нашлось три разных дефекта:
--   15 сделок  потеряли источник при переводе из БФЛ;
--    7 сделок  потеряли собственный источник Автоправо;
--   17 сделок  с указанным рекомендателем лежат в «Другое» вместо
--              «Рекомендации» — два источника используются как синонимы;
--   12 сделок  это повторные обращения, то есть не привлечение вообще.
--
-- ВАЖНО ПРО ПРИРОДУ ЭТОЙ ТАБЛИЦЫ. Это НЕ механизм исправления данных, а
-- разовый слепок ручного разбора. Битрикс не правится: при следующем импорте
-- ap_deals перезапишется, а эта таблица останется и продолжит показывать
-- сверку. Если дефект окажется массовым, правила надо будет встроить в
-- импорт, и тогда таблица уйдёт.
--
-- ПОЧЕМУ ПЕРЕВОДЫ ИЗ БФЛ НЕ ЗАЧИСЛЯЮТСЯ В ОДНОИМЁННЫЕ КАНАЛЫ АВТОПРАВА.
-- У Автоправа есть свой канал «2.2 Заявки 2гис» со своим расходом. Если
-- зачислить туда 11 сделок, пришедших через 2ГИС направления БФЛ, его CPO
-- станет втрое лучше реального — договоры будут, а расход на них списан в
-- другом направлении. Поэтому такие сделки идут в отдельную группу
-- «Перевод из БФЛ» с указанием исходного источника: видно, откуда пришло, и
-- при этом не испорчена экономика собственных каналов.
-- ============================================================================

create table if not exists ap_deal_source_overrides (
  deal_id bigint primary key,
  -- Источник, которым сделка является на самом деле. null — разобрать не
  -- удалось, нужен человек.
  real_source text,
  -- Для рекомендаций: кто привёл. Это постоянные клиенты и сотрудники,
  -- которые регулярно приводят знакомых.
  recommender text,
  -- Тип дефекта: рекомендация / перевод из БФЛ / повторное обращение /
  -- подмена источника / источник не определён / разовый обзвон базы.
  kind text not null,
  -- Исходный текст поля «Дополнительно об источнике» — чтобы разбор можно
  -- было перепроверить, не возвращаясь к выгрузке.
  source_note text,
  created_at timestamptz not null default now()
);

alter table ap_deal_source_overrides enable row level security;
drop policy if exists "authenticated_select" on ap_deal_source_overrides;
create policy "authenticated_select" on ap_deal_source_overrides for select using (auth.uid() is not null);
drop policy if exists "admin_write" on ap_deal_source_overrides;
create policy "admin_write" on ap_deal_source_overrides for all using (is_admin()) with check (is_admin());

