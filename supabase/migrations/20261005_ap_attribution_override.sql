-- ============================================================================
-- Сводка «было → стало»: главный экран сверки
--
-- Слева то, что сейчас показывает приложение, справа то, чем сделка является
-- на самом деле. Считаются только выигранные сделки из разобранной выгрузки.
-- ============================================================================
drop view if exists ap_attribution_diff;
create view ap_attribution_diff with (security_invoker = true) as
select
  coalesce(d.source_name, '— источник пуст —') as сейчас_в_приложении,
  coalesce(o.real_source, '— не определён —') as на_самом_деле,
  o.kind as тип,
  count(*)::integer as сделок
from ap_deal_source_overrides o
left join ap_deals d on d.deal_id = o.deal_id
group by 1, 2, 3;

-- ============================================================================
-- Итог по источникам: сколько договоров приписано сейчас и сколько должно
-- ============================================================================
drop view if exists ap_attribution_totals;
create view ap_attribution_totals with (security_invoker = true) as
with сейчас as (
  select coalesce(d.source_name, '— источник пуст —') as источник, count(*)::integer as n
  from ap_deal_source_overrides o
  left join ap_deals d on d.deal_id = o.deal_id
  group by 1
),
должно as (
  select coalesce(real_source, '— не определён —') as источник, count(*)::integer as n
  from ap_deal_source_overrides
  group by 1
),
ключи as (
  select источник from сейчас union select источник from должно
)
select
  к.источник,
  coalesce(с.n, 0) as сейчас_сделок,
  coalesce(д.n, 0) as должно_быть,
  coalesce(д.n, 0) - coalesce(с.n, 0) as разница
from ключи к
left join сейчас с on с.источник = к.источник
left join должно д on д.источник = к.источник;

-- ============================================================================
-- Рекомендации в разрезе рекомендателей — то, ради чего всё затевалось
-- ============================================================================
drop view if exists ap_recommenders;
create view ap_recommenders with (security_invoker = true) as
select
  coalesce(recommender, '— не указан —') as рекомендатель,
  count(*)::integer as сделок,
  round(100.0 * count(*) / sum(count(*)) over (), 1) as доля_рекомендаций,
  min(d.deal_created_date) as первая_сделка,
  max(d.deal_created_date) as последняя_сделка
from ap_deal_source_overrides o
left join ap_deals d on d.deal_id = o.deal_id
where o.kind = 'рекомендация'
group by 1;

-- ============================================================================
-- Построчно — для проверки руками
-- ============================================================================
drop view if exists ap_attribution_rows;
create view ap_attribution_rows with (security_invoker = true) as
select
  o.deal_id,
  d.deal_created_date as дата,
  coalesce(d.source_name, '— нет в базе —') as сейчас_в_приложении,
  coalesce(o.real_source, '— не определён —') as на_самом_деле,
  coalesce(o.recommender, '') as рекомендатель,
  o.kind as тип,
  o.source_note as исходный_текст
from ap_deal_source_overrides o
left join ap_deals d on d.deal_id = o.deal_id;
