-- Три источника выводятся из статистики. Причины у всех разные.
--
-- ПРД и МАКАРОВ — каналы признаны мусорными и отключены, но флаг в приложении
-- снять забыли, поэтому они продолжают попадать в выборки. ПРД даёт 550 лидов
-- при 9,5 квала на сотню, Макаров — 67 при 14,9. Для оценки того, чего ждать
-- дальше, их в базе быть не должно: канала больше нет.
--
-- BFLEADS — случай принципиально иной и методически важный. Эти лиды приходят
-- УЖЕ ПОСЛЕ колл-центра другой компании, то есть предварительно обработанными.
-- Отсюда аномалии, которые мы видели и не могли объяснить:
--     охват 90,6%  — выше всех, при 19,3 попытки на лида;
--     квал 34,0%   — заметно выше среднего 28,9.
-- Это не качество обзвона, а свойство базы: с людьми уже поговорили до нас.
-- Руководитель направления добавляет, что до встречи такие лиды доходят
-- плохо, то есть выигрыш на входе теряется дальше по воронке.
--
-- ЧТО ИЗМЕНИТСЯ В РАНЕЕ НАЗВАННЫХ ЦИФРАХ. Проверил заранее, чтобы не
-- пересказывать прежние выводы как новые:
--   * «разговор даёт квал в 50-55% случаев» — почти не сдвинется. У BFLeads
--     конверсия разговора 61,5% против средних 63,2%, то есть он был около
--     середины и бенчмарк не завышал;
--   * доля достигнутых и квал на сотню лидов — снизятся, и правильно:
--     90,6% охвата по предобработанной базе сравнивать с обычной нельзя;
--   * средние по ПРД и Макарову уходят вверх, так как оба были сильно ниже.
--
-- Напоминание о границах исключений: фильтруются витрины про воронку лидов и
-- дозвон. Витрины по встречам не трогаются — если лид дошёл до встречи,
-- встреча была настоящей.
-- ============================================================================

