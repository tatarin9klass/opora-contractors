-- ============================================================================
-- Кабинет перестаёт быть отчётом и становится инструментом.
--
-- ЧТО БЫЛО НЕ ТАК. Экраны отвечали на вопрос «как дела»: передано столько,
-- план такой, брак такой. Это нужно руководителю направления, чтобы решать
-- про людей и бюджеты. А руководителю отдела нужен ответ на другой вопрос —
-- «что делать сегодня»: кого дёрнуть, какую сделку спасать, где горит.
-- Такой ответ в кабинете был ровно один и прятался на третьем клике.
--
-- ЧТО ДАЁТ ЭТА МИГРАЦИЯ. Две вещи, из которых собираются все списки дел:
--
--   rop_portal_deals — сами открытые сделки отдела, поштучно. Их три
--   сотни, это ничтожный объём, и отдавать их целиком дешевле, чем заводить
--   отдельную витрину под каждый вопрос. Любой новый список дел после этого
--   делается на экране, без похода в базу.
--
--   rop_portal_pace — сколько дней этап держит сделку и какая доля уходит
--   с него в ОКС. Конверсия говорит «сколько дошло», скорость — «почему
--   медленно», и вторым руководитель управляет напрямую.
-- ============================================================================

-- --- Открытые сделки поштучно ------------------------------------------------
drop view if exists rop_portal_deals;
create view rop_portal_deals as
select
  d.deal_id, d.title, d.отдел, d.менеджер, d.работает,
  d.stage_id, d.этап, d.состояние, d.группа,
  d.создана, d.последнее_движение,
  d.дней_без_движения, d.возраст_дней, d.порог_дней, d.залежалась,
  d.чек, d.сумма_поля, d.есть_бфл, d.есть_аз, d.есть_вки
from rop_portfolio_deal d
where rop_can_read()
  and (is_staff() or d.отдел = current_rop_team());

revoke all on rop_portal_deals from anon;
grant select on rop_portal_deals to authenticated;

comment on view rop_portal_deals is
  'Открытые сделки отдела поштучно. Из них кабинет собирает списки дел: '
  'залежавшиеся, встречи без предложения, зависшие на приёмке.';

-- --- Скорость этапов ---------------------------------------------------------
drop view if exists rop_portal_pace;
create view rop_portal_pace as
select
  p.stage_id,
  s.стадия as этап,
  p.переходов,
  p.медиана_дней,
  p.дней_у_80_процентов,
  l.порог_дней,
  w.сделок as сделок_в_расчёте,
  w.доля_дошедших
from rop_stage_pace p
left join rop_stage_limit l on l.stage_id = p.stage_id
left join rop_stage_win_rate w on w.stage_id = p.stage_id
left join rop_stage_since s on s.stage_id = p.stage_id
where rop_can_read();

revoke all on rop_portal_pace from anon;
grant select on rop_portal_pace to authenticated;

