-- ============================================================================
-- Развёртка на маркетинг и рекомендации показывала РОПу одно «прочее».
--
-- ТА ЖЕ ПРИЧИНА, ЧТО И У ПУСТОГО КАБИНЕТА, но с другой стороны. Витрины
-- починены предыдущей миграцией и теперь читают таблицы правами владельца.
-- А вот функция rop_source_group(), которой они размечают источник, —
-- обычная: внутри вьюхи она выполняется от имени того, кто спрашивает.
--
-- Функция читает справочник префиксов rop_source_prefixes, на нём стоит
-- политика staff_select. Для роли rop справочник пуст, ни один префикс не
-- совпадает, и срабатывает coalesce(..., 'прочее') — вся воронка уезжает в
-- «прочее». Ошибка тем неприятнее, что выглядит как правда о данных:
-- «источники не размечены», а не «функции не видно справочника».
--
-- Под админом этого не видно: у него is_staff() истинна, справочник
-- читается, разметка верная. Опять ловится только входом под самим РОПом.
--
-- ЧТО ДЕЛАЕМ. Функция становится security definer. Это безопасно и по
-- сути правильно: она не отдаёт содержимое справочника, а возвращает одно
-- слово — группу для строки, которую ей передали. Справочник префиксов
-- остаётся закрытым, как и был.
--
-- Альтернатива — открыть rop_source_prefixes всем залогиненным — хуже:
-- справочник пришлось бы раздать и подрядчикам, которым он не нужен ни
-- при каких условиях.
--
-- РОДСТВЕННИКОВ У ЭТОЙ ОШИБКИ НЕТ. Проверил все функции схемы: читает
-- таблицу и при этом не является definer — только эта. rop_product_group()
-- разбирает название продукта строкой и ничего не читает, поэтому АЗ, ВКИ
-- и ФПА считались верно даже со сломанной разметкой источников.
-- ============================================================================

create or replace function rop_source_group(source_name text)
returns text
language sql
security definer
set search_path = public
stable
as $$
  select coalesce(
    (select p.source_group
     from rop_source_prefixes p
     where lower(coalesce(source_name, '')) like p.prefix || '%'
     -- Длинный префикс выигрывает у короткого: «ofbfl-» должен побеждать
     -- «of», если такой когда-нибудь появится.
     order by length(p.prefix) desc
     limit 1),
    'прочее'
  );
$$;

comment on function rop_source_group(text) is
  'Группа источника сделки: маркетинг, рекомендации или прочее. '
  'security definer — чтобы работать внутри витрин кабинета РОПа, у '
  'которого доступа к справочнику префиксов нет и быть не должно.';

