-- ============================================================================
-- Источник сделки: если лида нет, берём из самой сделки.
--
-- ЧТО СЛОМАЛОСЬ. После первого импорта у 157 сделок из 569 источник оказался
-- пустым — больше четверти. Руководитель направления сказал прямо: сделок без
-- источника не бывает. Он прав, и ошибка моя: импорт брал источник ТОЛЬКО из
-- лида-родителя. У сделки есть собственное поле SOURCE_ID, я его даже
-- запрашивал, но не использовал.
--
-- Совпадение трёх чисел — 157 сделок без источника, 157 не проходивших через
-- «Встреча проведена» и 157 стоящих на «Передано в Делопроизводство» —
-- указывает на одну и ту же группу: сделки, попавшие в воронку не из лида.
-- У них источник есть, просто лежит в другом месте.
--
-- ЗАЧЕМ ХРАНИТЬ, ОТКУДА ВЗЯЛСЯ ИСТОЧНИК. Чтобы следующая такая дыра была
-- видна сразу, а не через месяц по косвенным совпадениям. Колонка source_from
-- отвечает на вопрос «почему у этой сделки такой источник» без раскопок.
-- ============================================================================

alter table rop_deals
  add column if not exists source_id text,
  add column if not exists source_from text;

comment on column rop_deals.source_from is
  'Откуда взят источник: «лид» — из лида-родителя (основной случай), '
  '«сделка» — из собственного поля сделки, когда лида нет, NULL — не нашли '
  'нигде. Последнее означает ошибку импорта или нового вида связи: таких '
  'строк быть не должно.';

