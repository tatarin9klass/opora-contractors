-- ============================================================================
-- Архивные стадии — это и есть действующие. Приводим памятку к реальности.
--
-- ЧТО ВСКРЫЛОСЬ. В воронке есть стадии с суффиксом «(Архив)», и именно на
-- них висят все заявки, а у их «действующих» двойников заявок ноль:
--
--   Звонок: Не отвечает более месяца (Архив)   3559 заявок   ← живая
--   Не отвечает больше месяца                     0 заявок   ← пустая
--   Звонок: Не интересно (условно) (Архив)     1465 заявок   ← живая
--   Звонок: Не интересно (условно)                0 заявок   ← пустая
--
-- То есть «(Архив)» — не историческая копия, а текущее название стадии.
-- Обе живые стадии числились как «в работе», потому что в памятке лежали их
-- пустые двойники, а сами они под сопоставление не подошли. В итоге
-- подрядчикам не засчитывалось полторы тысячи квалов, а три с половиной
-- тысячи закрытых заявок выглядели живыми.
--
-- ПОЧЕМУ НЕ СОВПАЛО. Ключ сопоставления снимал приставку «Звонок:», но не
-- знал ни про суффикс «(Архив)», ни про то, что в одном названии «более
-- месяца», а в другом «больше месяца».
--
-- ЭТО ТРЕТИЙ СЛУЧАЙ ОДНОЙ ОШИБКИ. Сначала не совпала приставка, теперь
-- суффикс и синоним. Поэтому лечится опять ключом, а не перечислением
-- названий: перечислять — значит возвращаться сюда после каждого
-- переименования в Битриксе, причём узнавать о нём от подрядчика.
-- ============================================================================

-- Суть названия. Снимается всё, что не меняет смысла: приставка «Звонок:»,
-- суффикс «(Архив)», написание «более/больше месяца».
create or replace function bfl_stage_key(name text)
returns text language sql immutable as $$
  select btrim(
    replace(
      regexp_replace(
        regexp_replace(lower(coalesce(name, '')), '^звонок\s*:?\s*', ''),
        '\s*\(архив\)\s*$', ''
      ),
      'более месяца', 'больше месяца'
    )
  );
$$;

comment on function bfl_stage_key(text) is
  'Название стадии, приведённое к сути: без приставки «Звонок:», без '
  'суффикса «(Архив)», с единым написанием «больше месяца». По нему стадии '
  'сопоставляются с памяткой, чтобы переименование в Битриксе не ломало '
  'исход молча.';

-- --- Исходы по ключу, заново ------------------------------------------------
update bfl_lead_stage_guide set outcome_group = 'квал', is_qual = true
where bfl_stage_key(status_name) in (
  'назначение встречи',
  'встреча назначена - точное время',
  'не интересно (условно)',
  'успех'
);

update bfl_lead_stage_guide set outcome_group = 'в работе', is_qual = false
where bfl_stage_key(status_name) in (
  'новый лид',
  'взят в работу',
  'не удалось дозвониться',
  'скорозвон',
  'дозвонились'
);

update bfl_lead_stage_guide set outcome_group = 'брак', is_qual = false
where bfl_stage_key(status_name) in (
  'ошибочная заявка',
  'другой регион',
  'не отвечает больше месяца',
  'дубль',
  'нл'
);

-- --- Живая стадия забирает описание и место у пустого двойника --------------
-- Описание переносится БЕЗ пометки про архив: раз заявки идут именно сюда,
-- стадия действующая, и называть её архивной значило бы сбивать с толку.
update bfl_lead_stage_guide g
set description = src.description
from (
  select distinct on (bfl_stage_key(status_name))
    bfl_stage_key(status_name) as k, description
  from bfl_lead_stage_guide
  where description not like 'Описание этой стадии пока не заполнено%'
  order by bfl_stage_key(status_name), sort_order
) src
where bfl_stage_key(g.status_name) = src.k
  and g.description like 'Описание этой стадии пока не заполнено%';

update bfl_lead_stage_guide g
set sort_order = src.sort_order
from (
  select distinct on (bfl_stage_key(status_name))
    bfl_stage_key(status_name) as k, sort_order
  from bfl_lead_stage_guide
  where sort_order < 900
  order by bfl_stage_key(status_name), sort_order
) src
where bfl_stage_key(g.status_name) = src.k
  and g.sort_order = 900;

-- --- Точная формулировка для «Не интересно (условно)» -----------------------
-- Прежний текст говорил «человек отказался идти дальше», и это неверно по
-- сути процесса. Руководитель направления объяснил: заявка качественная,
-- она засчитана квалом, а встречу не продали на НАШЕЙ стороне, в колл-центре.
-- Через пару месяцев такие заявки пробуют реанимировать.
--
-- Для подрядчика разница принципиальная. Прочитав «клиент отказался», он
-- решит, что привёл сомнительного человека, и станет оправдываться там, где
-- оправдываться не в чем. Полторы тысячи заявок — слишком много, чтобы
-- оставлять это на догадки.
update bfl_lead_stage_guide
set description =
  'Заявка квалифицирована: человек подходит по профилю, разговор состоялся. '
  'Договориться о встрече не получилось — это недоработка нашего '
  'колл-центра, не ваша. Заявка засчитана и отправлена в архив; через '
  'пару месяцев мы вернёмся к таким клиентам ещё раз.'
where bfl_stage_key(status_name) = 'не интересно (условно)';

-- --- Точная формулировка для «НЛ» ------------------------------------------
-- Прежний текст называл эту стадию технической и не несущей смысла для
-- подрядчика. Это неверно: на ней 3740 заявок, вторая по величине группа, и
-- для подрядчика она как раз самая содержательная из всего брака. «Нецелевой
-- лид» означает, что разговор состоялся, но человек не прошёл квалификацию —
-- чаще всего из-за слишком маленькой суммы долга.
--
-- То есть это прямая обратная связь по настройкам кампании, а не мусор. Чем
-- точнее подрядчик поймёт причину, тем выше шанс, что он подкрутит таргетинг
-- сам, не дожидаясь разговора с нами.
update bfl_lead_stage_guide
set description =
  'Разговор состоялся, но человек не прошёл квалификацию: чаще всего сумма '
  'долга слишком мала для банкротства, иногда — отказ разговаривать по '
  'существу. Заявка не оплачивается. Это самый полезный сигнал о качестве '
  'трафика: если таких заявок много, имеет смысл пересмотреть параметры '
  'кампании — аудиторию, объявления, формулировки на посадочной странице.'
where bfl_stage_key(status_name) = 'нл';

-- --- Пустые двойники убираем -----------------------------------------------
-- Памятку читает подрядчик, и две почти одинаковые строки, одна из которых
-- не встречается ни в одной заявке, — это шум, по которому он придёт
-- спрашивать, чем они отличаются. Удаляем только ту форму названия, по
-- которой нет НИ ОДНОЙ заявки и у которой есть живой двойник по ключу.
--
-- Стадия без заявок и без двойника (например «Скорозвон», куда сейчас никого
-- не передают) остаётся: она не дубль, и завтра по ней заявки появятся.
delete from bfl_lead_stage_guide dead
where not exists (
    select 1 from bfl_lead_timings l where l.status_name = dead.status_name
  )
  and exists (
    select 1
    from bfl_lead_stage_guide alive
    join bfl_lead_timings l on l.status_name = alive.status_name
    where bfl_stage_key(alive.status_name) = bfl_stage_key(dead.status_name)
      and alive.status_name <> dead.status_name
  );

-- --- Что получилось --------------------------------------------------------
do $$
declare
  leftovers text;
  summary text;
begin
  select string_agg(status_name, ', ' order by status_name)
  into leftovers
  from bfl_lead_stage_guide
  where description like 'Описание этой стадии пока не заполнено%';
  if leftovers is not null then
    raise notice 'Остались стадии без описания (заполни на экране «Доступы подрядчиков»): %',
      leftovers;
  else
    raise notice 'Все стадии описаны.';
  end if;

  select string_agg(outcome_group || ': ' || n, ' | ' order by outcome_group)
  into summary
  from (
    select g.outcome_group, count(l.lead_id) as n
    from bfl_lead_stage_guide g
    left join bfl_lead_timings l on l.status_name = g.status_name
    group by g.outcome_group
  ) t;
  raise notice 'Заявок по исходам: %', summary;
end $$;

