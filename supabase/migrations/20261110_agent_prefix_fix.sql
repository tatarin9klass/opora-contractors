-- ============================================================================
-- Префикс источника: разделителем может быть не только дефис.
--
-- ЧТО БЫЛО НЕ ТАК. Правило требовало дефис сразу после префикса
-- («agbfl-…»), а живые агентские источники названы иначе: «Agbfl - от
-- Лонеки», «Agbfl - Пришел от АГЕНТА» — с пробелом перед дефисом. Из-за
-- одного пробела 227 агентских лидов числились в группе «прочее», и
-- таблица префиксов показывала, что через агентский канал не пришло
-- вообще ничего. То есть главная колонка кабинета — «Мимо», доля лидов
-- мимо своего канала, — показывала сто процентов у всех.
--
-- ПОЧЕМУ НЕ ВЕРНУТЬСЯ К ПРОСТОМУ «НАЧИНАЕТСЯ С ПРЕФИКСА». Потому что
-- префикс «r» тогда совпадает с «RC_GENERATOR» и с любым названием на
-- букву «р». Нужна середина: префикс, за которым идёт разделитель —
-- дефис, пробел или подчёркивание.
--
-- Проверено на живых названиях:
--   «Agbfl - от Лонеки»                     → agbfl
--   «ofbfl-Сайт ОПОРА (заявка)»             → ofbfl
--   «R-bfl-Рекомендация из ОКС на БФЛ»      → r
--   «OP-bfl-Звонок на номера ОП»            → op
--   «RC_GENERATOR»                          → прочее
-- ============================================================================
create or replace function agent_prefix(source_name text)
returns text language sql stable as $$
  select coalesce(
    (select p.prefix
     from rop_source_prefixes p
     where lower(coalesce(source_name, '')) ~ ('^' || p.prefix || '[ _-]')
        or lower(coalesce(source_name, '')) = p.prefix
     order by length(p.prefix) desc
     limit 1),
    'прочее'
  );
$$;

comment on function agent_prefix(text) is
  'Префикс источника по его названию: «Agbfl - от Лонеки» → agbfl. После '
  'префикса обязан идти разделитель (дефис, пробел или подчёркивание), '
  'иначе «r» совпадает с «RC_GENERATOR».';

