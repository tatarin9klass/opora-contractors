-- ============================================================================
-- Последний неизмеренный отрезок: от прихода лида до первого звонка.
--
-- ПОЧЕМУ ЭТО ПОНАДОБИЛОСЬ ИМЕННО СЕЙЧАС. Стратифицированный часовой разрез
-- опроверг утреннюю гипотезу и породил новую. Внутри ПЕРВЫХ попыток доля
-- разговоров растёт от 12,58% в девять утра до 26,98% в шесть вечера —
-- монотонно, вдвое. В агрегате всё выглядело наоборот только потому, что
-- утром доля первых попыток 16-17% от всех звонков, а днём 2,6-4,8%: утро не
-- лучше по времени, оно богаче свежими лидами. Парадокс Симпсона в чистом
-- виде.
--
-- На повторных попытках времени суток нет вовсе: 6,3-9,4% во втором стратуме
-- и 1,7-2,4% в третьем, без тренда. Значит час влияет ТОЛЬКО на первый
-- звонок, и вопрос сужается до одного: когда звонить новому лиду.
--
-- РАЗВИЛКА, КОТОРУЮ НАДО РАЗРЕШИТЬ. Час первого звонка почти совпадает с
-- часом прихода лида — человек оставил заявку в семь вечера, ему в семь и
-- позвонили. Поэтому неясно, что работает:
--   время звонка    — вечером люди дома и берут трубку; тогда выгодно
--                     придерживать и утренние заявки до вечера;
--   состояние лида  — вечером заявки оставляют те, кто свободен, и они же
--                     легко отвечают; тогда придерживать нечего, важно лишь
--                     не тянуть.
-- Разводится сравнением внутри одного часа прихода: лиды, пришедшие утром, у
-- которых первый звонок был сразу, против тех, до кого добрались к вечеру.
--
-- ПРО ВРЕМЯ СОЗДАНИЯ. created_at берётся из системного поля Битрикса
-- DATE_CREATE, у которого часовой пояс проставлен верно — в отличие от
-- пользовательского поля даты встречи, где нашлось смещение на четыре часа.
-- Если в разрезе по часам прихода обнаружится странный сдвиг пика, проверять
-- надо в первую очередь это.
-- ============================================================================

drop view if exists bfl_lead_first_attempt cascade;
create view bfl_lead_first_attempt with (security_invoker = true) as
with ranked as (
  select
    c.lead_id,
    c.started_at,
    c.has_recording,
    c.duration_sec,
    c.responsible_name,
    row_number() over (partition by c.lead_id order by c.started_at, c.id) as rn
  from bfl_lead_calls c
  where bfl_call_is_attempt(c.direction, c.completed)
    and c.started_at is not null
)
select
  l.lead_id,
  l.source_marker,
  l.created_at as лид_пришёл,
  r.started_at as первый_звонок,
  r.responsible_name as кто_звонил_первым,
  bfl_call_answered(r.has_recording, r.duration_sec) as дозвонились_сразу,
  bfl_call_dialogue(r.has_recording, r.duration_sec) as поговорили_сразу,
  extract(hour from (l.created_at at time zone 'Asia/Novosibirsk'))::integer as час_прихода,
  extract(hour from (r.started_at at time zone 'Asia/Novosibirsk'))::integer as час_первого_звонка,
  round(extract(epoch from (r.started_at - l.created_at)) / 60.0, 1) as минут_до_звонка,
  (l.qualified_at is not null) as стал_квалом
from bfl_lead_timings l
left join ranked r on r.lead_id = l.lead_id and r.rn = 1
where l.source_marker is not null
  and l.source_marker not in (select source_marker from bfl_excluded_sources);

-- ============================================================================
-- Главное: сколько стоит задержка первого звонка
-- ============================================================================
drop view if exists bfl_speed_to_lead;
create view bfl_speed_to_lead with (security_invoker = true) as
select
  case
    when первый_звонок is null then '9. не позвонили ни разу'
    when минут_до_звонка < 0 then '0. звонок раньше лида (проверить)'
    when минут_до_звонка < 5 then '1. до 5 минут'
    when минут_до_звонка < 15 then '2. 5-15 минут'
    when минут_до_звонка < 60 then '3. 15-60 минут'
    when минут_до_звонка < 240 then '4. 1-4 часа'
    when минут_до_звонка < 1440 then '5. 4-24 часа'
    when минут_до_звонка < 4320 then '6. 1-3 дня'
    else '7. позже 3 дней'
  end as задержка,
  count(*)::integer as лидов,
  count(*) filter (where дозвонились_сразу)::integer as дозвонились_с_первого,
  round(100.0 * count(*) filter (where дозвонились_сразу) / nullif(count(*), 0), 1)
    as доля_дозвона,
  count(*) filter (where поговорили_сразу)::integer as поговорили_с_первого,
  round(100.0 * count(*) filter (where поговорили_сразу) / nullif(count(*), 0), 1)
    as доля_разговоров,
  count(*) filter (where стал_квалом)::integer as квалов,
  round(100.0 * count(*) filter (where стал_квалом) / nullif(count(*), 0), 1)
    as конверсия_в_квал
from bfl_lead_first_attempt
group by 1;

-- ============================================================================
-- Разрешение развилки: время звонка или состояние лида
--
-- Внутри каждого окна прихода сравниваются лиды, которым позвонили быстро, и
-- те, до кого добрались позже в тот же день.
--
--   если у пришедших УТРОМ поздний звонок даёт результат лучше раннего —
--       работает время суток, и утренние заявки выгодно придерживать;
--   если быстрый звонок лучше в любом окне прихода —
--       работает свежесть лида, придерживать нельзя ни в коем случае, а
--       вечерний эффект объясняется тем, кто именно пишет по вечерам.
-- ============================================================================
drop view if exists bfl_speed_vs_hour;
create view bfl_speed_vs_hour with (security_invoker = true) as
select
  case
    when час_прихода < 12 then '1. лид пришёл утром (до 12)'
    when час_прихода < 16 then '2. лид пришёл днём (12-16)'
    when час_прихода < 20 then '3. лид пришёл вечером (16-20)'
    else '4. лид пришёл ночью'
  end as окно_прихода,
  case
    when первый_звонок is null then '9. не позвонили'
    when минут_до_звонка < 60 then '1. позвонили в течение часа'
    when минут_до_звонка < 480 then '2. позвонили через 1-8 часов'
    when минут_до_звонка < 1440 then '3. позвонили в пределах суток'
    else '4. позже суток'
  end as когда_позвонили,
  count(*)::integer as лидов,
  round(100.0 * count(*) filter (where дозвонились_сразу) / nullif(count(*), 0), 1)
    as доля_дозвона,
  round(100.0 * count(*) filter (where поговорили_сразу) / nullif(count(*), 0), 1)
    as доля_разговоров,
  round(100.0 * count(*) filter (where стал_квалом) / nullif(count(*), 0), 1)
    as конверсия_в_квал
from bfl_lead_first_attempt
group by 1, 2;

-- ============================================================================
-- Когда вообще приходят лиды и когда до них доходят руки
--
-- Нужна, чтобы оценить размер вечерней задачи: если заметная доля заявок
-- падает после 17:00, а первый звонок по ним уходит на утро, это прямая
-- потеря — вечерний первый звонок даёт 26,98% разговоров против 12,58%
-- утреннего.
-- ============================================================================
drop view if exists bfl_lead_arrival_profile;
create view bfl_lead_arrival_profile with (security_invoker = true) as
select
  час_прихода,
  count(*)::integer as лидов,
  count(*) filter (where первый_звонок is not null)::integer as набрали,
  round((percentile_cont(0.5) within group (order by минут_до_звонка))::numeric, 0)
    as медиана_минут_до_звонка,
  count(*) filter (
    where час_первого_звонка is not null and час_первого_звонка < час_прихода
  )::integer as позвонили_только_на_следующий_день,
  round(100.0 * count(*) filter (where поговорили_сразу) / nullif(count(*), 0), 1)
    as доля_разговоров_с_первого,
  round(100.0 * count(*) filter (where стал_квалом) / nullif(count(*), 0), 1)
    as конверсия_в_квал
from bfl_lead_first_attempt
group by 1;
